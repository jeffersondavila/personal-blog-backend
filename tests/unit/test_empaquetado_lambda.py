def test_los_timestamps_del_arbol_no_afectan_al_zip(tmp_path: Path) -> None:
    """G1: dos arboles identicos con `mtime` distintos dan el mismo ZIP."""
    primero = _arbol_valido(tmp_path / "primero")
    segundo = _arbol_valido(tmp_path / "segundo")
    for ruta in sorted(segundo.rglob("*")):
        if ruta.is_file():
            os.utime(ruta, (1_000_000_000, 1_000_000_000))

    zip_a = tmp_path / "a.zip"
    zip_b = tmp_path / "b.zip"
    escribir_zip(recolectar_entradas(primero), zip_a)
    escribir_zip(recolectar_entradas(segundo), zip_b)

    assert zip_a.read_bytes() == zip_b.read_bytes()


def test_las_entradas_van_en_orden_lexicografico(tmp_path: Path) -> None:
    """G2: el orden de entrega no altera el orden dentro del ZIP."""
    raiz = _arbol_valido(tmp_path / "arbol")
    entradas = recolectar_entradas(raiz)
    destino = tmp_path / "a.zip"

    escribir_zip(reversed(entradas), destino)

    with zipfile.ZipFile(destino) as archivo:
        assert archivo.namelist() == sorted(entrada.ruta for entrada in entradas)


def test_los_permisos_y_la_fecha_se_normalizan(tmp_path: Path) -> None:
    """G3 y C-024: modo `0644`, sistema Unix, fecha minima del formato ZIP."""
    raiz = _arbol_valido(tmp_path / "arbol")
    destino = tmp_path / "a.zip"

    escribir_zip(recolectar_entradas(raiz), destino)

    with zipfile.ZipFile(destino) as archivo:
        assert archivo.comment == b""
        for info in archivo.infolist():
            assert info.date_time == (1980, 1, 1, 0, 0, 0)
            assert info.create_system == 3
            assert stat.S_IMODE(info.external_attr >> 16) == 0o644
            assert info.compress_type == zipfile.ZIP_DEFLATED


def test_dos_arboles_equivalentes_producen_el_mismo_zip(tmp_path: Path) -> None:
    """H1: mismo contenido en directorios distintos, mismos bytes y mismo SHA."""
    zip_a = tmp_path / "a.zip"
    zip_b = tmp_path / "b.zip"
    escribir_zip(recolectar_entradas(_arbol_valido(tmp_path / "A")), zip_a)
    escribir_zip(recolectar_entradas(_arbol_valido(tmp_path / "B")), zip_b)

    assert zip_a.read_bytes() == zip_b.read_bytes()
    assert sha256_de(zip_a) == sha256_de(zip_b)


def test_un_cambio_real_cambia_el_checksum(tmp_path: Path) -> None:
    """I1: un byte distinto produce otro SHA-256."""
    primero = _arbol_valido(tmp_path / "A")
    segundo = _arbol_valido(tmp_path / "B")
    (segundo / "app" / "main.py").write_bytes(b"contenido distinto\n")

    zip_a = tmp_path / "a.zip"
    zip_b = tmp_path / "b.zip"
    escribir_zip(recolectar_entradas(primero), zip_a)
    escribir_zip(recolectar_entradas(segundo), zip_b)

    assert sha256_de(zip_a) != sha256_de(zip_b)


