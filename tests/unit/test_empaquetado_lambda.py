def test_el_manifiesto_es_deterministico(tmp_path: Path) -> None:
    """H2 depende de esto: sin reloj ni rutas locales dentro del manifiesto.

    Las dos construcciones viven en directorios distintos pero producen el
    **mismo nombre de artefacto**, igual que hace el flujo real: `construir`
    siempre escribe `NOMBRE_DEL_ARTEFACTO`, y lo que cambia entre `A` y `B` es
    unicamente el directorio de salida.
    """
    manifiestos = []
    for nombre in ("A", "B"):
        raiz = _arbol_valido(tmp_path / nombre / "arbol")
        destino = tmp_path / nombre / NOMBRE_DEL_ARTEFACTO
        entradas = recolectar_entradas(raiz)
        escribir_zip(entradas, destino)
        manifiestos.append(
            construir_manifiesto(
                entradas=entradas,
                artefacto=destino,
                medida=medir(entradas, destino),
                distribuciones=distribuciones_del_lock(LOCK_DE_EJEMPLO),
                lock=LOCK_DE_EJEMPLO,
                entorno={"python": "3.12.14", "pip": "25.0.1", "zlib": "1.2.11"},
            )
        )

