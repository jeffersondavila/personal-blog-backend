def test_el_checksum_y_el_manifiesto_no_viajan_dentro_del_zip(tmp_path: Path) -> None:
    """Evita el artefacto autorreferencial: la metadata vive fuera del ZIP."""
    raiz = _arbol_valido(tmp_path / "arbol")
    destino = tmp_path / "a.zip"
    entradas = recolectar_entradas(raiz)
    escribir_zip(entradas, destino)
    (tmp_path / "manifiesto.json").write_text("{}", encoding="utf-8")
    (tmp_path / "a.zip.sha256").write_text(f"{sha256_de(destino)}  a.zip\n", encoding="utf-8")

    with zipfile.ZipFile(destino) as archivo:
        nombres = archivo.namelist()

    assert nombres == sorted(entrada.ruta for entrada in entradas)
    assert not [nombre for nombre in nombres if "manifiesto" in nombre or ".sha256" in nombre]
