#: Cabecera ELF de 64 bits, little endian. `e_machine` vive en el offset 18.
_ELF_X86_64 = 62
_ELF_AARCH64 = 183


def _elf(maquina: int) -> bytes:
    """Construye una cabecera ELF64 valida con la arquitectura indicada."""
    cabecera = bytearray(64)
    cabecera[0:4] = b"\x7fELF"
    cabecera[4] = 2  # ELFCLASS64
    cabecera[5] = 1  # ELFDATA2LSB
    cabecera[6] = 1  # EV_CURRENT
    cabecera[16:18] = (3).to_bytes(2, "little")  # ET_DYN
    cabecera[18:20] = maquina.to_bytes(2, "little")
    return bytes(cabecera)


def _escribir(raiz: Path, ruta: str, contenido: bytes = b"contenido\n") -> Path:
    """Crea `ruta` bajo `raiz` con los directorios intermedios necesarios."""
    destino = raiz / ruta
    destino.parent.mkdir(parents=True, exist_ok=True)
    destino.write_bytes(contenido)
    return destino


def _arbol_valido(raiz: Path) -> Path:
    """Arbol minimo que satisface el *layout* y el inventario de ejemplo."""
    _escribir(raiz, "app/__init__.py")
    _escribir(raiz, "app/main.py")
    _escribir(raiz, "app/lambda_handler.py")
    _escribir(raiz, "fastapi/__init__.py")
    _escribir(raiz, "fastapi-0.141.1.dist-info/METADATA")
    _escribir(raiz, "mangum/__init__.py")
    _escribir(raiz, "mangum-0.22.0.dist-info/METADATA")
    _escribir(raiz, "argon2/__init__.py")
    _escribir(raiz, "argon2_cffi-25.1.0.dist-info/METADATA")
    return raiz


def _rutas(raiz: Path) -> list[str]:
    return [entrada.ruta for entrada in recolectar_entradas(raiz)]


